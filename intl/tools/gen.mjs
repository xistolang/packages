// Generates intl's locale data (data/*.ts) from Node's own Intl (ICU): node is the oracle, nothing is downloaded.
// usage: node tools/gen.mjs   (rewrites data/locales.ts, number.ts, datetime.ts, collation.ts)
//        INTL_LOCALES=pt-BR,en-GB node tools/gen.mjs   (other locales: the first is the fallback; fewer locales, less data
//        in each program that uses a formatter)
// Each locale's data is a few functions per feature (mostly one string literal each: a table read by src/table.ts),
// reached only through the dispatchers at the end of each file from the formatter that uses them, so a program pays
// only for the features it uses. tools/verify.mjs then checks the package against Node's Intl.
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const out = path.join(here, "..", "data");
const LOCALES = (process.env.INTL_LOCALES || "en-US,pt-BR").split(","); // index 0 is the fallback
const id = (l) => l.replace("-", "_");
const header = `// Generated by tools/gen.mjs from Node ${process.version} (ICU ${process.versions.icu}, CLDR ${process.versions.cldr}); do not edit.\n`;
const q = (s) => JSON.stringify(s);
// numbers as printable ASCII digits of base 90 ('#' is 0, '\\' skipped): src/ reads them back
const enc1 = (n) => { if (n < 0 || n >= 90) throw new Error("digit " + n); let c = 35 + n; if (c >= 92) c++; return String.fromCharCode(c); };
const enc2 = (n) => enc1(Math.floor(n / 90)) + enc1(n % 90);
const enc3 = (n) => enc1(Math.floor(n / 8100)) + enc2(n % 8100);

// ---------------------------------------------------------------- numbers
function numberData() {
  let src = header + `import { NumLocale } from "../src/types";\n\n`;
  const currencies = Intl.supportedValuesOf("currency");
  for (const l of LOCALES) {
    const parts = (o, v) => new Intl.NumberFormat(l, o).formatToParts(v);
    const p = parts({}, -12345.5);
    const dec = p.find((x) => x.type === "decimal").value;
    const group = p.find((x) => x.type === "group").value;
    const minus = p.find((x) => x.type === "minusSign").value;
    const minGroup = new Intl.NumberFormat(l).format(1234).includes(group) ? 1 : 2;
    // percent and currency: what comes before and after the number (the sign goes before all of it)
    const around = (o) => {
      const ps = parts(o, 5).map((x) => (x.type === "currency" ? "¤" : x.value));
      const types = parts(o, 5).map((x) => x.type);
      const i = types.indexOf("integer");
      let j = i;
      while (j + 1 < types.length && ["integer", "group", "decimal", "fraction"].includes(types[j + 1])) j++;
      return [ps.slice(0, i).join(""), ps.slice(j + 1).join("")];
    };
    const [pctPre, pctSuf] = around({ style: "percent" });
    const [curPre, curSuf] = around({ style: "currency", currency: "USD" });
    // the space ICU puts between a currency symbol that ends in a letter and the digits (XYZ 5.00, but $5.00)
    const alphaSpace = (() => {
      const s = new Intl.NumberFormat(l, { style: "currency", currency: "XYZ" }).format(5);
      return s.startsWith("XYZ") ? s.slice(3, s.indexOf("5")) : "";
    })();
    const nan = new Intl.NumberFormat(l).format(NaN);
    const inf = new Intl.NumberFormat(l).format(Infinity);
    src += `export function numLocale_${id(l)}(): NumLocale {\n  return new NumLocale(${[dec, group, minus, pctPre, pctSuf, curPre, curSuf, alphaSpace, nan, inf].map(q).join(", ")}, ${minGroup});\n}\n`;
    // currency symbols that are not the code, as ";CODE=symbol" (src/number.ts looks them up)
    let syms = "", narrow = "";
    for (const c of currencies) {
      const sym = (d) => new Intl.NumberFormat(l, { style: "currency", currency: c, currencyDisplay: d }).formatToParts(1).find((x) => x.type === "currency").value;
      if (sym("symbol") !== c) syms += `;${c}=${sym("symbol")}`;
      if (sym("narrowSymbol") !== sym("symbol")) narrow += `;${c}=${sym("narrowSymbol")}`;
      if (sym("symbol").includes(";") || sym("narrowSymbol").includes(";")) throw new Error("; in a symbol");
    }
    src += `export function numSymbols_${id(l)}(): string {\n  return ${q(syms + ";")};\n}\n`;
    src += `export function numNarrowSymbols_${id(l)}(): string {\n  return ${q(narrow + ";")};\n}\n`;
  }
  // the currencies whose fraction digits are not 2, as "CODEn" (ISO 4217, as ICU)
  let digits = "";
  for (const c of currencies) {
    const d = new Intl.NumberFormat("en", { style: "currency", currency: c }).resolvedOptions().maximumFractionDigits;
    if (d !== 2) digits += c + d;
  }
  src += `export function currencyDigitsTable(): string {\n  return ${q(digits)};\n}\n`;
  src += dispatch("numLocale", "NumLocale", "") + dispatch("numSymbols", "string", "") + dispatch("numNarrowSymbols", "string", "");
  fs.writeFileSync(path.join(out, "number.ts"), src);
}
function dispatch(name, type, args) {
  return `export function ${name}(i: int): ${type} {\n  switch (i) {\n${LOCALES.map((l, i) => i ? `    case ${i}: return ${name}_${id(l)}(${args});\n` : "").join("")}    default: return ${name}_${id(LOCALES[0])}(${args});\n  }\n}\n`;
}

// ---------------------------------------------------------------- dates
// Component patterns: a pattern per date shape (which of year, month, day, weekday, and how wide) and per time shape
// (hour, minute, second, 12 or 24 hours, zone name), joined by a glue that depends on the date shape (with the pairs
// that take another listed). Tokens: {y} {yy} {M1} {M2} {MMM} {MMMM} {MMMMM} (L: the standalone names) {d1} {d2} {E}
// {EEEE} {EEEEE} (c: standalone) {h1} {h2} {H1} {H2} {m1} {m2} {s1} {s2} {a} {z} {zl}; a digit is the field's width.
const REF = Date.UTC(2026, 2, 5, 4, 7, 9); // Thursday 5 March 2026, 04:07:09 UTC: one-digit day, month, hour, minute, second
const WD_CLS = [null, "short", "long", "narrow"];
function names(l) {
  const f = (o, d) => new Intl.DateTimeFormat(l, { timeZone: "UTC", ...o }).formatToParts(d);
  const pick = (ps, t) => ps.find((x) => x.type === t).value;
  const r = {};
  for (const w of ["short", "long", "narrow"]) {
    r["M" + w] = []; r["L" + w] = []; r["E" + w] = []; r["c" + w] = [];
    for (let m = 0; m < 12; m++) {
      const d = new Date(Date.UTC(2026, m, 5));
      r["M" + w].push(pick(f({ month: w, day: "numeric" }, d), "month"));
      r["L" + w].push(pick(f({ month: w }, d), "month"));
    }
    for (let k = 0; k < 7; k++) { // 2026-03-01 is a Sunday
      const d = new Date(Date.UTC(2026, 2, 1 + k));
      r["E" + w].push(pick(f({ weekday: w, day: "numeric", month: "long" }, d), "weekday"));
      r["c" + w].push(pick(f({ weekday: w }, d), "weekday"));
    }
  }
  r.am = pick(f({ hour: "numeric", hourCycle: "h12" }, new Date(REF)), "dayPeriod");
  r.pm = pick(f({ hour: "numeric", hourCycle: "h12" }, new Date(REF + 12 * 3600e3)), "dayPeriod");
  return r;
}
function tokens(l, nm, opts, date) {
  const ps = new Intl.DateTimeFormat(l, { timeZone: "UTC", ...opts }).formatToParts(date ?? new Date(REF));
  let s = "";
  for (const p of ps) {
    const v = p.value;
    switch (p.type) {
      case "literal": s += v; break;
      case "year": s += v.length === 2 ? "{yy}" : "{y}"; break;
      case "month":
        if (/^\d+$/.test(v)) s += `{M${v.length}}`;
        else {
          let t = null;
          const ws = opts.month && opts.month !== "numeric" ? [opts.month] : ["long", "short", "narrow"];
          const ks = opts.month ? ["L", "M"] : ["M", "L"]; // a month alone takes the standalone name
          for (const w of ws) for (const k of opts.day || opts.year || opts.weekday ? ["M", "L"] : ks) if (!t && nm[k + w][2] === v) t = k.repeat(w === "short" ? 3 : w === "long" ? 4 : 5);
          if (!t) throw new Error(`month ${v} in ${l} ${JSON.stringify(opts)}`);
          s += `{${t}}`;
        }
        break;
      case "day": s += `{d${v.length}}`; break;
      case "weekday": {
        let t = null;
        const alone = !opts.day && !opts.month && !opts.year && !opts.dateStyle;
        for (const w of opts.weekday ? [opts.weekday] : ["long", "short", "narrow"]) for (const k of alone ? ["c", "E"] : ["E", "c"])
          if (!t && nm[k + w][4] === v) t = w === "short" ? k : w === "long" ? k.repeat(4) : k.repeat(5);
        if (!t) throw new Error(`weekday ${v}`);
        s += `{${t}}`;
        break;
      }
      case "hour": s += `{${opts.hourCycle === "h12" || (opts.hourCycle === undefined && /[AP]M/.test(ps.map((x) => x.value).join(""))) ? "h" : "H"}${v.length}}`; break;
      case "minute": s += `{m${v.length}}`; break;
      case "second": s += `{s${v.length}}`; break;
      case "dayPeriod": s += "{a}"; break;
      case "timeZoneName": s += opts.timeStyle === "full" ? "{zl}" : "{z}"; break;
      default: throw new Error("part " + p.type);
    }
  }
  return s;
}
// a date shape: year (none, numeric, 2-digit), month (none, numeric, 2-digit, short, long, narrow), day (as year),
// weekday (none, short, long, narrow): ((y * 6 + M) * 3 + d) * 4 + w, 216 shapes (src/datetime.ts computes the same)
const NUMW = [null, "numeric", "2-digit"];
const MONTHW = [null, "numeric", "2-digit", "short", "long", "narrow"];
function dateKeyOpts(k) {
  const w = k % 4, d = Math.floor(k / 4) % 3, m = Math.floor(k / 12) % 6, y = Math.floor(k / 72);
  const o = {};
  if (y) o.year = NUMW[y];
  if (m) o.month = MONTHW[m];
  if (d) o.day = NUMW[d];
  if (w) o.weekday = WD_CLS[w];
  return o;
}
// a time shape: hour, minute, second (none, numeric, 2-digit), 12 or 24 hours, a zone name (none, a name: short or
// long, an offset: shortOffset or longOffset): (((h * 3 + m) * 3 + s) * 2 + h23) * 5 + z, 270 shapes
const DATE_KEYS = 216, TIME_KEYS = 270;
const ZN = [null, "short", "long", "shortOffset", "longOffset"];
function timeKeyOpts(k) {
  const z = k % 5, h23 = Math.floor(k / 5) % 2, s = Math.floor(k / 10) % 3, m = Math.floor(k / 30) % 3, h = Math.floor(k / 90);
  const o = {};
  if (h) o.hour = NUMW[h];
  if (m) o.minute = NUMW[m];
  if (s) o.second = NUMW[s];
  o.hourCycle = h23 ? "h23" : "h12";
  if (z) o.timeZoneName = ZN[z];
  return o;
}
function datetimeData() {
  let src = header + `import { DtLocale } from "../src/types";\n\n`;
  for (const l of LOCALES) {
    const nm = names(l);
    const date = [], time = [], glue = [], zglue = [], glueX = [], byGlue = [];
    for (let k = 1; k < DATE_KEYS; k++) date[k] = tokens(l, nm, dateKeyOpts(k));
    for (let k = 10; k < TIME_KEYS; k++) time[k] = tokens(l, nm, timeKeyOpts(k));
    // the glue between a date shape and a time shape (mostly one per date shape: the others are kept as exceptions)
    // and between a date shape and a lone zone name
    for (let dk = 1; dk < DATE_KEYS; dk++) {
      for (let tk = 10; tk < TIME_KEYS; tk++) {
        const full = tokens(l, nm, { ...dateKeyOpts(dk), ...timeKeyOpts(tk) });
        const D = date[dk], T = time[tk];
        let g = null;
        if (full.startsWith(D) && full.endsWith(T) && full.length >= D.length + T.length) g = full.slice(D.length, full.length - T.length);
        if (g === null) { glueX[dk * TIME_KEYS + tk] = "=" + full; continue; } // (not date + glue + time: the whole pattern)
        (byGlue[dk] ??= new Map()).set(g, [...(byGlue[dk].get(g) || []), tk]);
      }
      // the glue of most time shapes, and the others as exceptions (en-US: "Thu 4 AM" but "Thu, 4:07:09 AM")
      const common = [...byGlue[dk]].sort((a, b) => b[1].length - a[1].length);
      glue[dk] = common[0][0];
      for (const [g, tks] of common.slice(1)) for (const tk of tks) glueX[dk * TIME_KEYS + tk] = g;
      for (let z = 1; z < 5; z++) {
        const zn = ZN[z];
        const zfull = tokens(l, nm, { ...dateKeyOpts(dk), timeZoneName: zn });
        if (!zfull.startsWith(date[dk]) || !zfull.endsWith("{z}")) throw new Error(`${l}: date ${dk} + zone: ${zfull}`);
        zglue[dk * 5 + z] = zfull.slice(date[dk].length, zfull.length - 3);
      }
    }
    // a zone name alone (no date, no time): the date defaults, as Node
    const styles = [];
    const ST = ["full", "long", "medium", "short"];
    for (const s of ST) styles.push(tokens(l, nm, { dateStyle: s }));
    for (const hc of ["h12", "h23"]) for (const s of ST) styles.push(tokens(l, nm, { timeStyle: s, hourCycle: hc }));
    for (let i = 0; i < 4; i++) { // the glue of dateStyle i with any timeStyle (checked the same)
      let g = null;
      for (let j = 0; j < 4; j++) for (const hc of ["h12", "h23"]) {
        const full = tokens(l, nm, { dateStyle: ST[i], timeStyle: ST[j], hourCycle: hc });
        const D = styles[i], T = styles[(hc === "h12" ? 4 : 8) + j];
        if (!full.startsWith(D) || !full.endsWith(T)) throw new Error(`${l}: style ${i}/${j}: ${full}`);
        const gg = full.slice(D.length, full.length - T.length);
        if (g !== null && g !== gg) throw new Error(`${l}: style glue ${i}`);
        g = gg;
      }
      styles.push(g);
    }
    const defH12 = new Intl.DateTimeFormat(l, { hour: "numeric" }).resolvedOptions().hourCycle === "h12";
    const nmlist = (k) => q(nm[k].join("|"));
    const same = (a, b) => nm[a].join("|") === nm[b].join("|");
    src += `export function dtLocale_${id(l)}(): DtLocale {\n  return new DtLocale(\n`;
    src += `    ${nmlist("Mlong")},\n    ${nmlist("Mshort")},\n    ${nmlist("Mnarrow")},\n`;
    src += `    ${same("Mlong", "Llong") && same("Mshort", "Lshort") && same("Mnarrow", "Lnarrow") ? '""' : q([nm.Llong, nm.Lshort, nm.Lnarrow].map((x) => x.join("|")).join("#"))},\n`;
    src += `    ${nmlist("Elong")},\n    ${nmlist("Eshort")},\n    ${nmlist("Enarrow")},\n`;
    src += `    ${same("Elong", "clong") && same("Eshort", "cshort") && same("Enarrow", "cnarrow") ? '""' : q([nm.clong, nm.cshort, nm.cnarrow].map((x) => x.join("|")).join("#"))},\n`;
    src += `    ${q(nm.am)}, ${q(nm.pm)}, ${defH12});\n}\n`;
    // every pattern once, in one string; an ASCII index gives each shape its pattern's number (2 base-90 digits):
    // date shapes, time shapes, the glue of each date shape, the zone glue of each (date shape, zone kind), styles
    const pats = [""], pid = new Map([["", 0]]);
    const idOf = (v) => { if (v === undefined) v = ""; if (!pid.has(v)) { pid.set(v, pats.length); pats.push(v); } return pid.get(v); };
    let index = "";
    const put = (v) => { index += enc2(idOf(v)); };
    for (let k = 0; k < DATE_KEYS; k++) put(date[k]);
    for (let k = 0; k < TIME_KEYS; k++) put(time[k]);
    for (let k = 0; k < DATE_KEYS; k++) put(glue[k]);
    for (let k = 0; k < DATE_KEYS * 5; k++) put(zglue[k]);
    for (let k = 0; k < 16; k++) put(styles[k]);
    // the (date shape, time shape) pairs whose glue is another: 3 base-90 digits of the pair, 2 of the pattern
    let except = "";
    glueX.forEach((v, k) => { if (v !== undefined) except += enc1(Math.floor(k / 8100)) + enc1(Math.floor(k / 90) % 90) + enc1(k % 90) + enc2(idOf(v)); });
    let list = "", offs = "";
    for (const p of pats) { offs += enc3(list.length); list += p; }
    offs += enc3(list.length);
    if ([...list].some((c) => c.codePointAt(0) > 0xffff)) throw new Error("a pattern outside the BMP");
    src += `export function dtPatterns_${id(l)}(): string {\n  return ${q(list)};\n}\n`;
    src += `export function dtIndex_${id(l)}(): string {\n  return ${q(offs + "!" + index + "!" + except)};\n}\n`;
    // the 16 style patterns again, on their own: a program that passes dateStyle / timeStyle as literals compiles
    // only the one it uses (xisto folds the if over a literal slot), not this locale's whole pattern table
    src += `export function dtStyle_${id(l)}(slot: int): string {\n`;
    for (let k = 0; k < 16; k++) src += `  if (slot === ${k}) return ${q(styles[k])};\n`;
    src += `  return "";\n}\n`;
    src += zoneNames(l);
  }
  src += `// dtIndex: the patterns' offsets in dtPatterns (3 digits each), "!", the pattern of each date shape (${DATE_KEYS}), time\n// shape (${TIME_KEYS}), date shape's glue (${DATE_KEYS}), (date shape, zone kind)'s zone glue (${DATE_KEYS * 5}) and style (16), 2 digits\n// each, "!", the (date, time) pairs with another glue: 3 digits of date * ${TIME_KEYS} + time, 2 of the pattern\n`;
  src += dispatch("dtLocale", "DtLocale", "") + dispatch("dtPatterns", "string", "") + dispatch("dtIndex", "string", "") + dispatch("dtZoneNames", "string", "") +
    `export function dtStyle(i: int, slot: int): string {\n  switch (i) {\n${LOCALES.map((l, i) => i ? `    case ${i}: return dtStyle_${id(l)}(slot);\n` : "").join("")}    default: return dtStyle_${id(LOCALES[0])}(slot);\n  }\n}\n`;
  fs.writeFileSync(path.join(out, "datetime.ts"), src);
}
// the zones whose names are kept (others print as GMT-3 / GMT-03:00, as ICU does for a zone it has no name for)
const ZONES = ["UTC", "America/Sao_Paulo", "America/Fortaleza", "America/Recife", "America/Bahia", "America/Belem", "America/Maceio",
  "America/Araguaina", "America/Manaus", "America/Cuiaba", "America/Campo_Grande", "America/Porto_Velho", "America/Boa_Vista",
  "America/Rio_Branco", "America/Noronha", "America/New_York", "America/Chicago", "America/Denver", "America/Phoenix",
  "America/Los_Angeles", "America/Anchorage", "Pacific/Honolulu", "America/Toronto", "America/Vancouver", "America/Mexico_City",
  "America/Bogota", "America/Lima", "America/Caracas", "America/Santiago", "America/Argentina/Buenos_Aires", "America/Montevideo",
  "America/Asuncion", "Europe/London", "Europe/Lisbon", "Europe/Paris", "Europe/Berlin", "Europe/Madrid", "Europe/Rome",
  "Europe/Amsterdam", "Europe/Moscow", "Africa/Johannesburg", "Africa/Lagos", "Africa/Cairo", "Africa/Luanda", "Africa/Maputo",
  "Asia/Dubai", "Asia/Kolkata", "Asia/Shanghai", "Asia/Hong_Kong", "Asia/Singapore", "Asia/Tokyo", "Australia/Sydney"];
function offsetOf(zone, ms) {
  const p = new Intl.DateTimeFormat("en-US", { timeZone: zone, hourCycle: "h23", year: "numeric", month: "numeric", day: "numeric", hour: "numeric", minute: "numeric", second: "numeric" }).formatToParts(new Date(ms));
  const g = (t) => +p.find((x) => x.type === t).value;
  return (Date.UTC(g("year"), g("month") - 1, g("day"), g("hour"), g("minute"), g("second")) - Math.floor(ms / 1000) * 1000) / 60000;
}
function zoneNames(l) {
  // per zone: [standard short, standard long, daylight short, daylight long]; "" where ICU prints the GMT offset
  const rows = new Map();
  for (const z of ZONES) {
    const r = ["", "", "", ""];
    for (let y = 2000; y <= 2026; y++) for (const m of [0, 6]) {
      const ms = Date.UTC(y, m, 1, 12);
      const std = Math.min(offsetOf(z, Date.UTC(y, 0, 1)), offsetOf(z, Date.UTC(y, 6, 1)));
      const dst = offsetOf(z, ms) > std;
      for (const long of [false, true]) {
        const v = new Intl.DateTimeFormat(l, { timeZone: z, timeZoneName: long ? "long" : "short" }).formatToParts(new Date(ms)).find((x) => x.type === "timeZoneName").value;
        const off = new Intl.DateTimeFormat(l, { timeZone: z, timeZoneName: long ? "longOffset" : "shortOffset" }).formatToParts(new Date(ms)).find((x) => x.type === "timeZoneName").value;
        const i = (dst ? 2 : 0) + (long ? 1 : 0);
        if (v !== off) r[i] = v;
      }
    }
    const key = r.join("|");
    if (key !== "|||") rows.set(key, [...(rows.get(key) || []), z]);
  }
  // ";zone=standard short,standard long,daylight short,daylight long" ("" where ICU prints the GMT offset)
  let t = "";
  for (const [key, zs] of rows) for (const z of zs) t += `;${z}=${key.split("|").join(",")}`;
  if (/[;,=]/.test([...rows.keys()].join(""))) throw new Error("separator in a zone name");
  return `export function dtZoneNames_${id(l)}(): string {\n  return ${q(t + ";")};\n}\n`;
}

// ---------------------------------------------------------------- collation
// ICU's root collation (pt and en have no tailoring, checked) for U+0020..U+017F: per code point its weights, as
// four printable ASCII characters: primary (2, base 90), secondary, tertiary (each base 90, +32), or an expansion
// (two code points, e.g. ß = ss) marked by '~' and the two characters' table indexes.
const CHARS = [];
for (let c = 0x20; c < 0x180; c++) if (c < 0x7f || c >= 0xa0) CHARS.push(c);
function collationData() {
  const base = new Intl.Collator("en", { sensitivity: "base" });
  const accent = new Intl.Collator("en", { sensitivity: "accent" });
  const full = new Intl.Collator("en");
  for (const l of LOCALES) { // no tailoring: every locale orders as root
    const c = new Intl.Collator(l);
    const s = CHARS.map((x) => String.fromCharCode(x));
    for (let i = 0; i < s.length; i++) for (let j = 0; j < s.length; j += 7) if (c.compare(s[i], s[j]) !== full.compare(s[i], s[j])) throw new Error(`${l} is tailored`);
  }
  const str = CHARS.map((x) => String.fromCharCode(x));
  // expansions: a character equal (at the base level) to two others
  const exp = new Map();
  const singles = str.filter((x) => base.compare(x, "") !== 0);
  for (const x of str) {
    if (singles.some((y) => y !== x && y.charCodeAt(0) < 0x80 && base.compare(x, y) === 0)) continue;
    if (base.compare(x, "") === 0) continue;
    // its own class unless two letters equal it
    for (const a of "abcdefghijklmnopqrstuvwxyz") for (const b of "abcdefghijklmnopqrstuvwxyz") if (!exp.has(x) && base.compare(x, a + b) === 0) exp.set(x, a + b);
  }
  const simple = str.filter((x) => !exp.has(x) && base.compare(x, "") !== 0).sort(full.compare);
  // primary: the class of characters equal at the base level; secondary: the accent group within it; tertiary: the
  // variant within that (a and A one variant, ª another), and whether the character is upper case
  const w = new Map(); // char -> [p, s, t, upper]
  let p = 0, prev = null, sPrev = null, si = 0, reps = [];
  for (const x of simple) {
    if (prev === null || base.compare(prev, x) !== 0) { p++; si = 0; sPrev = x; reps = []; }
    else if (accent.compare(sPrev, x) !== 0) { si++; sPrev = x; reps = []; }
    const rep = x.toLowerCase();
    if (!reps.includes(rep)) reps.push(rep);
    w.set(x, [p, si, reps.indexOf(rep), x !== x.toLowerCase() ? 1 : 0]);
    prev = x;
  }
  let table = "";
  for (const x of str) {
    if (exp.has(x)) {
      // an expansion: its two letters (in its case) and flags: 1 a secondary difference (ß > ss), 2 a tertiary one (ĳ > ij)
      let [a, b] = exp.get(x);
      if (x !== x.toLowerCase()) { a = a.toUpperCase(); b = b.toUpperCase(); }
      const flags = accent.compare(x, a + b) !== 0 ? 1 : full.compare(x, a + b) !== 0 ? 2 : 0;
      table += "~" + enc1(str.indexOf(a)) + enc1(str.indexOf(b)) + enc1(flags);
    } else if (!w.has(x)) table += enc2(0) + enc1(0) + enc1(0); // ignorable
    else { const [pp, ss, tt, up] = w.get(x); table += enc2(pp) + enc1(ss) + enc1(tt * 2 + up); }
  }
  let src = header + `// ICU root collation weights of U+0020..U+007E and U+00A0..U+017F, 4 characters each (see tools/gen.mjs)\n`;
  src += `export function collationTable(): string {\n  return ${q(table)};\n}\n`;
  src += `// the primary weight after every character of the table (code points outside it sort after, by code point)\nexport function collationTop(): int {\n  return ${p + 1};\n}\n`;
  fs.writeFileSync(path.join(out, "collation.ts"), src);
}

