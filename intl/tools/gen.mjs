// a locale tag resolves to the locale of the same tag, else to the first of the same language, else to the fallback
function localesData() {
  let src = header + `\n/** The index of the data for a locale tag (${LOCALES.join(", ")}; anything else: ${LOCALES[0]}). */\n`;
  src += `export function localeIndex(tag: string | null): int {\n  if (tag === null || tag === undefined) return 0;\n  const t = tag.toLowerCase().replace("_", "-");\n`;
  LOCALES.forEach((l, i) => { src += `  if (t === ${q(l.toLowerCase())}) return ${i};\n`; });
  const langs = new Map();
  LOCALES.forEach((l, i) => { const lang = l.split("-")[0].toLowerCase(); if (!langs.has(lang)) langs.set(lang, i); });
  for (const [lang, i] of langs) if (i !== 0) src += `  if (t === ${q(lang)} || t.startsWith(${q(lang + "-")})) return ${i};\n`;
  src += `  return 0;\n}\n`;
  src += `\n/** The tag of the data a locale resolved to (resolvedOptions().locale). */\nexport function localeTag(i: int): string {\n  switch (i) {\n`;
  LOCALES.forEach((l, i) => { if (i) src += `    case ${i}: return ${q(l)};\n`; });
  src += `    default: return ${q(LOCALES[0])};\n  }\n}\n`;
  fs.writeFileSync(path.join(out, "locales.ts"), src);
}

